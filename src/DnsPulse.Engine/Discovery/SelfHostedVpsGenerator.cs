namespace DnsPulse.Engine.Discovery;

/// <summary>
/// Input parameters for generating an authenticated, IP-allowlisted self-hosted Smart-DNS/SNI-Proxy VPS deployment bundle.
/// </summary>
public sealed record SelfHostedVpsOptions
{
    public required string HostName { get; init; }

    public required string ServerIpAddress { get; init; }

    /// <summary>
    /// Explicit client IP/CIDR allowlist. Open-resolver masks (<c>0.0.0.0/0</c>, <c>::/0</c>) and empty lists are rejected.
    /// </summary>
    public required IReadOnlyList<string> AllowedClientCidrs { get; init; }

    public IReadOnlyList<string> TargetGeoUnlockDomains { get; init; } = [];

    public string DohPath { get; init; } = "/dns-query";

    public int HttpsPort { get; init; } = 443;

    public int DotPort { get; init; } = 853;

    public string ProfileName { get; init; } = "My Self-Hosted DNS Pulse VPS";

    public ImmutableArray<byte> CertificateSha256Hash { get; init; } = [];
}

/// <summary>
/// Complete hardened deployment bundle generated by <see cref="SelfHostedVpsGenerator"/>.
/// </summary>
public sealed record SelfHostedVpsBundle
{
    public required string HostName { get; init; }

    public required string ServerIpAddress { get; init; }

    public required string BearerToken { get; init; }

    public required IReadOnlyList<string> AllowedClientCidrs { get; init; }

    public required string DockerComposeYaml { get; init; }

    public required string NginxConf { get; init; }

    public required string Corefile { get; init; }

    public required string AdGuardHomeYaml { get; init; }

    public required string UfwRulesScript { get; init; }

    [SuppressMessage("Design", "CA1056:URI-like properties should not be strings", Justification = "Stores raw sdns:// DNSCrypt stamp string.")]
    public required string DnsStampUri { get; init; }

    public required string ProfileJson { get; init; }

    public required DnsServerEntry ServerEntry { get; init; }
}

/// <summary>
/// Generates hardened, bearer-token authenticated and IP-allowlisted Docker + Nginx + CoreDNS/AdGuard + UFW
/// deployment bundles for private self-hosted VPS resolvers. Never generates an open public resolver.
/// </summary>
public sealed class SelfHostedVpsGenerator
{
    private const int BearerTokenEntropyBytes = 32;

    private static readonly JsonSerializerOptions ProfileJsonOptions = new()
    {
        WriteIndented = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase
    };

    /// <summary>
    /// Generates a complete hardened VPS deployment bundle with a fresh 256-bit cryptographic bearer token.
    /// </summary>
    [SuppressMessage("Performance", "CA1822:Mark members as static", Justification = "Injectable generator service instance API.")]
    public SelfHostedVpsBundle Generate(SelfHostedVpsOptions options)
    {
        ArgumentNullException.ThrowIfNull(options);
        ArgumentException.ThrowIfNullOrWhiteSpace(options.HostName);
        ArgumentException.ThrowIfNullOrWhiteSpace(options.ServerIpAddress);
        ArgumentNullException.ThrowIfNull(options.AllowedClientCidrs);

        string hostName = ValidateHostName(options.HostName);
        IPAddress serverIp = ValidateServerIp(options.ServerIpAddress);
        List<string> allowlist = ValidateAllowlist(options.AllowedClientCidrs);
        List<string> geoDomains = ValidateGeoDomains(options.TargetGeoUnlockDomains);

        if (options.HttpsPort is < 1 or > 65535)
        {
            throw new ArgumentOutOfRangeException(nameof(options), "HttpsPort must be between 1 and 65535.");
        }

        if (options.DotPort is < 1 or > 65535)
        {
            throw new ArgumentOutOfRangeException(nameof(options), "DotPort must be between 1 and 65535.");
        }

        string dohPath = NormalizeDohPath(options.DohPath);
        string bearerToken = GenerateBearerToken();
        string formattedIp = serverIp.ToString();

        string stampServerAddr = serverIp.AddressFamily == AddressFamily.InterNetworkV6
            ? (options.HttpsPort == 443
                ? string.Create(CultureInfo.InvariantCulture, $"[{formattedIp}]")
                : string.Create(CultureInfo.InvariantCulture, $"[{formattedIp}]:{options.HttpsPort}"))
            : (options.HttpsPort == 443
                ? formattedIp
                : string.Create(CultureInfo.InvariantCulture, $"{formattedIp}:{options.HttpsPort}"));

        string stampHostName = options.HttpsPort == 443
            ? hostName
            : string.Create(CultureInfo.InvariantCulture, $"{hostName}:{options.HttpsPort}");

        string bootstrapIp = serverIp.AddressFamily == AddressFamily.InterNetworkV6
            ? string.Create(CultureInfo.InvariantCulture, $"[{formattedIp}]")
            : formattedIp;

        ImmutableArray<ImmutableArray<byte>> hashes = !options.CertificateSha256Hash.IsDefaultOrEmpty
            ? [options.CertificateSha256Hash]
            : [];

        DnsStamp stamp = new()
        {
            Protocol = DnsStampProtocol.DoH,
            Properties = DnsStampFlags.DnsSec | DnsStampFlags.NoLog | DnsStampFlags.NoFilter,
            ServerAddress = stampServerAddr,
            Hashes = hashes,
            HostName = stampHostName,
            Path = dohPath,
            BootstrapIps = [bootstrapIp]
        };

        string dnsStampUri = DnsStampCodec.Encode(stamp);
        string dohUrl = options.HttpsPort == 443
            ? string.Create(CultureInfo.InvariantCulture, $"https://{hostName}{dohPath}")
            : string.Create(CultureInfo.InvariantCulture, $"https://{hostName}:{options.HttpsPort}{dohPath}");

        string dockerCompose = BuildDockerComposeYaml(options.HttpsPort, options.DotPort);
        string nginxConf = BuildNginxConf(hostName, dohPath, bearerToken, options.HttpsPort, allowlist, geoDomains);
        string corefile = BuildCorefile(geoDomains);
        string adGuardYaml = BuildAdGuardHomeYaml(allowlist);
        string ufwScript = BuildUfwRulesScript(allowlist, options.HttpsPort, options.DotPort);

        VpsProfileDocument profileDoc = new(
            Id: string.Create(CultureInfo.InvariantCulture, $"vps_{hostName}"),
            Name: string.IsNullOrWhiteSpace(options.ProfileName) ? hostName : options.ProfileName.Trim(),
            HostName: hostName,
            ServerIpAddress: formattedIp,
            DohUrl: dohUrl,
            DnsStampUri: dnsStampUri,
            BearerToken: bearerToken,
            AuthorizationHeader: string.Concat("Bearer ", bearerToken),
            AllowedClientCidrs: allowlist,
            TargetGeoUnlockDomains: geoDomains,
            TrustTier: TrustTier.Tier3CustomOrSelfHosted.ToString(),
            CreatedAtUtc: DateTimeOffset.UtcNow);

        string profileJson = JsonSerializer.Serialize(profileDoc, ProfileJsonOptions);

        DnsServerEntry serverEntry = new()
        {
            Id = profileDoc.Id,
            Name = profileDoc.Name,
            Provider = "Self-Hosted VPS",
            Protocol = DnsProtocol.DoH,
            TrustTier = TrustTier.Tier3CustomOrSelfHosted,
            PrimaryIp = formattedIp,
            DohUrl = dohUrl,
            DotHost = hostName,
            DnsStampUri = dnsStampUri,
            BootstrapIps = [formattedIp],
            Port = options.HttpsPort,
            Category = "Свои / Найденные",
            Country = "SELF",
            Tags = ["self-hosted", "authenticated", "doh", "sni-proxy"],
            Description = "Hardened private VPS DoH + SNI-proxy with bearer token and IP allowlist.",
            SupportsBypass = true,
            IsBuiltin = false,
            IsFavorite = false,
            IsSubscription = false,
            IsFreeUnlimited = true
        };

        return new SelfHostedVpsBundle
        {
            HostName = hostName,
            ServerIpAddress = formattedIp,
            BearerToken = bearerToken,
            AllowedClientCidrs = allowlist,
            DockerComposeYaml = dockerCompose,
            NginxConf = nginxConf,
            Corefile = corefile,
            AdGuardHomeYaml = adGuardYaml,
            UfwRulesScript = ufwScript,
            DnsStampUri = dnsStampUri,
            ProfileJson = profileJson,
            ServerEntry = serverEntry
        };
    }

    private static string GenerateBearerToken()
    {
        byte[] bytes = RandomNumberGenerator.GetBytes(BearerTokenEntropyBytes);
        return Convert.ToBase64String(bytes)
            .TrimEnd('=')
            .Replace('+', '-')
            .Replace('/', '_');
    }

    private static string ValidateHostName(string hostName)
    {
        string trimmed = hostName.Trim().TrimEnd('.');
        if (trimmed.Length is 0 or > 253 ||
            trimmed.Contains(' ', StringComparison.Ordinal) ||
            trimmed.Contains('/', StringComparison.Ordinal) ||
            trimmed.Contains('@', StringComparison.Ordinal) ||
            trimmed.Contains(':', StringComparison.Ordinal) ||
            Uri.CheckHostName(trimmed) == UriHostNameType.Unknown)
        {
            throw new ArgumentException("HostName must be a valid DNS hostname without scheme, port, or credentials.", nameof(hostName));
        }

        return trimmed;
    }

    private static IPAddress ValidateServerIp(string ipText)
    {
        if (!IPAddress.TryParse(ipText.AsSpan().Trim(), out IPAddress? ip))
        {
            throw new ArgumentException("ServerIpAddress must be a valid IPv4 or IPv6 address.", nameof(ipText));
        }

        if (ip.Equals(IPAddress.Any) || ip.Equals(IPAddress.IPv6Any))
        {
            throw new ArgumentException("ServerIpAddress cannot be unspecified (0.0.0.0 or ::).", nameof(ipText));
        }

        return ip;
    }

    private static List<string> ValidateAllowlist(IReadOnlyList<string> cidrs)
    {
        if (cidrs.Count == 0)
        {
            throw new ArgumentException(
                "AllowedClientCidrs must contain at least one explicit client IP or CIDR. Open public resolvers are forbidden.",
                nameof(cidrs));
        }

        List<string> normalized = new(cidrs.Count);
        foreach (string raw in cidrs)
        {
            if (string.IsNullOrWhiteSpace(raw))
            {
                continue;
            }

            string trimmed = raw.Trim();
            if (trimmed.Equals("*", StringComparison.Ordinal) ||
                trimmed.Equals("any", StringComparison.OrdinalIgnoreCase) ||
                trimmed.Equals("0.0.0.0/0", StringComparison.Ordinal) ||
                trimmed.Equals("::/0", StringComparison.Ordinal))
            {
                throw new ArgumentException(
                    string.Create(CultureInfo.InvariantCulture, $"Wildcard allowlist entry '{trimmed}' is forbidden; open public resolvers are disallowed."),
                    nameof(cidrs));
            }

            string[] parts = trimmed.Split('/');
            if (parts.Length > 2 || !IPAddress.TryParse(parts[0], out IPAddress? addr))
            {
                throw new ArgumentException(
                    string.Create(CultureInfo.InvariantCulture, $"Invalid CIDR or IP in AllowedClientCidrs: '{trimmed}'."),
                    nameof(cidrs));
            }

            int maxPrefix = addr.AddressFamily == AddressFamily.InterNetwork ? 32 : 128;
            int prefixLen = maxPrefix;
            if (parts.Length == 2)
            {
                if (!int.TryParse(parts[1], NumberStyles.None, CultureInfo.InvariantCulture, out prefixLen) ||
                    prefixLen <= 0 ||
                    prefixLen > maxPrefix)
                {
                    throw new ArgumentException(
                        string.Create(CultureInfo.InvariantCulture, $"Invalid or open-resolver prefix length in '{trimmed}'."),
                        nameof(cidrs));
                }
            }

            normalized.Add(string.Create(CultureInfo.InvariantCulture, $"{addr}/{prefixLen}"));
        }

        if (normalized.Count == 0)
        {
            throw new ArgumentException(
                "AllowedClientCidrs must contain at least one valid CIDR entry.",
                nameof(cidrs));
        }

        return normalized;
    }

    private static List<string> ValidateGeoDomains(IReadOnlyList<string> domains)
    {
        List<string> result = [];
        foreach (string raw in domains)
        {
            if (string.IsNullOrWhiteSpace(raw))
            {
                continue;
            }

            string cleaned = raw.Trim().TrimEnd('.');
            if (cleaned.Contains(' ', StringComparison.Ordinal) ||
                cleaned.Contains(';', StringComparison.Ordinal) ||
                cleaned.Contains('{', StringComparison.Ordinal) ||
                cleaned.Contains('}', StringComparison.Ordinal) ||
                cleaned.Contains('\n', StringComparison.Ordinal) ||
                cleaned.Contains('\r', StringComparison.Ordinal))
            {
                throw new ArgumentException(
                    string.Create(CultureInfo.InvariantCulture, $"Invalid domain '{cleaned}' in TargetGeoUnlockDomains."),
                    nameof(domains));
            }

            result.Add(cleaned);
        }

        return result;
    }

    private static string NormalizeDohPath(string? dohPath)
    {
        if (string.IsNullOrWhiteSpace(dohPath))
        {
            return "/dns-query";
        }

        string trimmed = dohPath.Trim();
        if (trimmed.Contains(' ', StringComparison.Ordinal) ||
            trimmed.Contains(';', StringComparison.Ordinal) ||
            trimmed.Contains('\n', StringComparison.Ordinal) ||
            trimmed.Contains('\r', StringComparison.Ordinal))
        {
            throw new ArgumentException("DohPath contains invalid characters.", nameof(dohPath));
        }

        return trimmed.StartsWith('/') ? trimmed : string.Concat("/", trimmed);
    }

    private static string BuildDockerComposeYaml(int httpsPort, int dotPort)
    {
        StringBuilder sb = new();
        sb.AppendLine("services:");
        sb.AppendLine("  coredns:");
        sb.AppendLine("    image: coredns/coredns:1.11.3");
        sb.AppendLine("    container_name: dnspulse-coredns");
        sb.AppendLine("    restart: unless-stopped");
        sb.AppendLine("    read_only: true");
        sb.AppendLine("    cap_drop:");
        sb.AppendLine("      - ALL");
        sb.AppendLine("    security_opt:");
        sb.AppendLine("      - no-new-privileges:true");
        sb.AppendLine("    command: -conf /etc/coredns/Corefile");
        sb.AppendLine("    volumes:");
        sb.AppendLine("      - ./Corefile:/etc/coredns/Corefile:ro");
        sb.AppendLine("    ports:");
        sb.AppendLine("      - \"127.0.0.1:5353:5353/udp\"");
        sb.AppendLine("      - \"127.0.0.1:5353:5353/tcp\"");
        sb.AppendLine();
        sb.AppendLine("  nginx-proxy:");
        sb.AppendLine("    image: nginx:1.27-alpine");
        sb.AppendLine("    container_name: dnspulse-nginx");
        sb.AppendLine("    restart: unless-stopped");
        sb.AppendLine("    read_only: true");
        sb.AppendLine("    cap_drop:");
        sb.AppendLine("      - ALL");
        sb.AppendLine("    cap_add:");
        sb.AppendLine("      - NET_BIND_SERVICE");
        sb.AppendLine("    security_opt:");
        sb.AppendLine("      - no-new-privileges:true");
        sb.AppendLine("    network_mode: host");
        sb.AppendLine("    volumes:");
        sb.AppendLine("      - ./nginx.conf:/etc/nginx/nginx.conf:ro");
        sb.AppendLine("      - ./certs:/etc/nginx/certs:ro");
        sb.AppendLine("      - /var/cache/nginx:/var/cache/nginx");
        sb.AppendLine("      - /var/run:/var/run");
        sb.AppendLine(CultureInfo.InvariantCulture, $"    # Exposes hardened authenticated endpoints on TCP {httpsPort} (DoH + SNI-Proxy) and TCP {dotPort} (DoT)");
        return sb.ToString();
    }

    private static string BuildNginxConf(
        string hostName,
        string dohPath,
        string bearerToken,
        int httpsPort,
        IReadOnlyList<string> allowlist,
        IReadOnlyList<string> geoDomains)
    {
        StringBuilder sb = new();
        sb.AppendLine("worker_processes auto;");
        sb.AppendLine("events { worker_connections 1024; }");
        sb.AppendLine();
        sb.AppendLine("stream {");
        sb.AppendLine("    map $ssl_preread_server_name $sni_upstream {");
        sb.AppendLine(CultureInfo.InvariantCulture, $"        {hostName} 127.0.0.1:8443;");
        foreach (string domain in geoDomains)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"        {domain} {domain}:443;");
        }

        sb.AppendLine("        default 127.0.0.1:8443;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    server {");
        sb.AppendLine(CultureInfo.InvariantCulture, $"        listen {httpsPort};");
        sb.AppendLine("        ssl_preread on;");
        foreach (string cidr in allowlist)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"        allow {cidr};");
        }

        sb.AppendLine("        deny all;");
        sb.AppendLine("        proxy_pass $sni_upstream;");
        sb.AppendLine("        proxy_connect_timeout 5s;");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("http {");
        sb.AppendLine("    server_tokens off;");
        sb.AppendLine();
        sb.AppendLine("    server {");
        sb.AppendLine("        listen 127.0.0.1:8443 ssl;");
        sb.AppendLine("        http2 on;");
        sb.AppendLine(CultureInfo.InvariantCulture, $"        server_name {hostName};");
        sb.AppendLine("        ssl_certificate /etc/nginx/certs/fullchain.pem;");
        sb.AppendLine("        ssl_certificate_key /etc/nginx/certs/privkey.pem;");
        sb.AppendLine("        ssl_protocols TLSv1.2 TLSv1.3;");
        sb.AppendLine();
        foreach (string cidr in allowlist)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"        allow {cidr};");
        }

        sb.AppendLine("        deny all;");
        sb.AppendLine();
        sb.AppendLine(CultureInfo.InvariantCulture, $"        location = {dohPath} {{");
        sb.AppendLine(CultureInfo.InvariantCulture, $"            if ($http_authorization != \"Bearer {bearerToken}\") {{");
        sb.AppendLine("                return 403;");
        sb.AppendLine("            }");
        sb.AppendLine("            proxy_pass http://127.0.0.1:8053/dns-query;");
        sb.AppendLine("            proxy_set_header Host $host;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        location / {");
        sb.AppendLine("            return 404;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string BuildCorefile(List<string> geoDomains)
    {
        StringBuilder sb = new();
        sb.AppendLine(".:5353 {");
        sb.AppendLine("    bind 127.0.0.1");
        sb.AppendLine("    errors");
        sb.AppendLine("    cache 300");
        sb.AppendLine("    loop");
        if (geoDomains.Count > 0)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"    # Scoped Geo-Unlock domains: {string.Join(", ", geoDomains)}");
        }

        sb.AppendLine("    forward . tls://1.1.1.1 tls://9.9.9.9 {");
        sb.AppendLine("        tls_servername one.one.one.one");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string BuildAdGuardHomeYaml(IReadOnlyList<string> allowlist)
    {
        StringBuilder sb = new();
        sb.AppendLine("http:");
        sb.AppendLine("  address: 127.0.0.1:3000");
        sb.AppendLine("dns:");
        sb.AppendLine("  bind_hosts:");
        sb.AppendLine("    - 127.0.0.1");
        sb.AppendLine("  port: 5353");
        sb.AppendLine("  ratelimit: 30");
        sb.AppendLine("  refuse_any: true");
        sb.AppendLine("  allowed_clients:");
        foreach (string cidr in allowlist)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"    - {cidr}");
        }

        sb.AppendLine("  upstream_dns:");
        sb.AppendLine("    - https://dns.quad9.net/dns-query");
        sb.AppendLine("    - tls://one.one.one.one");
        sb.AppendLine("  bootstrap_dns:");
        sb.AppendLine("    - 9.9.9.9");
        sb.AppendLine("    - 1.1.1.1");
        return sb.ToString();
    }

    private static string BuildUfwRulesScript(IReadOnlyList<string> allowlist, int httpsPort, int dotPort)
    {
        StringBuilder sb = new();
        sb.AppendLine("#!/usr/bin/env bash");
        sb.AppendLine("set -euo pipefail");
        sb.AppendLine("ufw --force reset");
        sb.AppendLine("ufw default deny incoming");
        sb.AppendLine("ufw default allow outgoing");
        sb.AppendLine("ufw limit 22/tcp");
        sb.AppendLine("ufw deny 53");
        foreach (string cidr in allowlist)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"ufw allow from {cidr} to any port {httpsPort} proto tcp");
            sb.AppendLine(CultureInfo.InvariantCulture, $"ufw allow from {cidr} to any port {dotPort} proto tcp");
        }

        sb.AppendLine("ufw --force enable");
        return sb.ToString();
    }

    private sealed record VpsProfileDocument(
        string Id,
        string Name,
        string HostName,
        string ServerIpAddress,
        string DohUrl,
        string DnsStampUri,
        string BearerToken,
        string AuthorizationHeader,
        IReadOnlyList<string> AllowedClientCidrs,
        IReadOnlyList<string> TargetGeoUnlockDomains,
        string TrustTier,
        DateTimeOffset CreatedAtUtc);
}
